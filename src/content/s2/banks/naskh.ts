/** حروف تُكتب على السطر (ص١٢٨) */
const ON_LINE = ['أ', 'ب', 'ت', 'ث', 'د', 'ذ', 'ط', 'ظ', 'ف', 'ك']
/** حروف ينزل جزء منها تحت السطر (ص١٢٨). استُبعدت الحروف المشتركة مع قوائم أخرى (ص، ض، ق، م، و، هـ) */
const UNDER_LINE = ['ج', 'ح', 'خ', 'ر', 'ز', 'س', 'ش', 'ع', 'غ', 'ل', 'ن', 'ي']
/** رؤوس مطموسة دائماً (ص١٢٨) */
const HEAD = ['ف', 'ق', 'و', 'ص', 'ض', 'ط', 'ظ']

const ON = 'كله على السطر'
const UNDER = 'جزء منه تحت السطر'
const ALL_UNDER = 'كله تحت السطر'

/** موضع الحرف بالنسبة للسطر */
export function makeNaskhLineQuestion(): ChoiceQuestion {
  const onLine = Math.random() < 0.5
  const l = pick(onLine ? ON_LINE : UNDER_LINE)
  return choiceQ(
    `s2-naskh-line-${l}`,
    `أين بيستقر حرف «**${l}**» بالنسبة للسطر عند كتابته بخط النسخ؟`,
    [
      onLine ? ON : UNDER,
      onLine
        ? `صح! «${l}» من الحروف اللي بتنكتب كلها على السطر (أ ب ت ث د ذ ط ظ ف ك).`
        : `صح! «${l}» من الحروف اللي بينزل جزء منها تحت السطر.`,
    ],
    [
      [
        onLine ? UNDER : ON,
        onLine ? `«${l}» ما بينزل منه شي تحت السطر؛ هو من حروف السطر.` : `«${l}» من الحروف اللي بينزل جزء منها تحت السطر.`,
      ],
      [ALL_UNDER, 'ما في حرف بينكتب كله تحت السطر؛ يا بيكون على السطر يا بينزل جزء منه.'],
    ],
  )
}

/** رأس الحرف مطموس دائماً */
export function makeNaskhHeadQuestion(): ChoiceQuestion {
  const l = pick(HEAD)
  return choiceQ(
    `s2-naskh-head-${l}`,
    `كيف بيكون رأس حرف «**${l}**» في خط النسخ؟`,
    ['مطموساً دائماً', `صح! «${l}» من الحروف اللي رؤوسها مطموسة دائماً (ف ق و م هـ ص ض ط ظ).`],
    [
      ['مفتوحاً دائماً', `رأس «${l}» بيكون مطموساً مش مفتوحاً.`],
      ['مطموساً بأول الكلمة بس', `رأس «${l}» مطموس دائماً بكل مواضعه، مش بأول الكلمة بس.`],
    ],
  )
}

