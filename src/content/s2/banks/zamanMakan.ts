const EYN_TEXT: Record<Eyn, string> = {
  fath: 'مفتوحة',
  damm: 'مضمومة',
  kasr: 'مكسورة',
  faa: '',
  lam: '',
}

const wazn = (e: Eyn) => (e === 'kasr' || e === 'faa' ? 'مَفْعِل' : 'مَفْعَل')

function rightWhy(x: Derived): string {
  if (x.eyn === 'faa') return `الفعل «${x.verb}» معتل الفاء (أوله واو)، فوزنه مَفْعِل: ${x.ism}.`
  if (x.eyn === 'lam') return `الفعل «${x.verb}» معتل اللام (آخره حرف علة)، فوزنه مَفْعَل: ${x.ism}.`
  return `عين المضارع «${x.mud}» ${EYN_TEXT[x.eyn]}، فالوزن ${wazn(x.eyn)}: ${x.ism}.`
}

/** صوغ اسم الزمان أو المكان من فعل ثلاثي */
export function makeMakanFormQuestion(): ChoiceQuestion {
  const x = pick(DERIVED)
  const i = DERIVED.indexOf(x)
  const wrongs: [string, string][] = []
  if (x.alt)
    wrongs.push([
      x.alt,
      x.eyn === 'faa'
        ? `«${x.verb}» معتل الفاء، فوزنه مَفْعِل مش مَفْعَل.`
        : `عين المضارع «${x.mud}» ${EYN_TEXT[x.eyn]}، فالوزن ${wazn(x.eyn)} مش الوزن الثاني.`,
    ])
  wrongs.push([x.fa, `«${x.fa}» اسم الفاعل؛ بيدل على اللي فعل الفعل، مش على مكانه أو زمانه.`])
  wrongs.push([x.mf, `«${x.mf}» اسم المفعول؛ بيدل على اللي وقع عليه الفعل. واسم الزمان والمكان بيبدأ بميم مفتوحة وبوزن مَفْعَل أو مَفْعِل.`])
  return choiceQ(
    `s2-zm-form-${i}`,
    `صوغي اسم الزمان أو المكان من الفعل «**${x.verb}**» (مضارعه: ${x.mud}).`,
    [x.ism, `صح! ${rightWhy(x)}`],
    wrongs,
  )
}

