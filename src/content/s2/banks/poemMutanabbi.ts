/** سؤال معنى كلمة من أبيات المتنبي */
export function makePoemVocabQuestion(): Question {
  const v = pick(POEM_VOCAB)
  const others = shuffled(POEM_VOCAB.filter((x) => x.w !== v.w)).slice(0, 3)
  return choiceQ(
    `s2-poem-vocab-${v.w}`,
    `ما معنى «${v.w}» في أبيات المتنبي عن الحمّى؟`,
    [v.m, `صح! معنى «${v.w}» هو «${v.m}».`],
    others.map((o): [string, string] => [o.m, `هذا معنى «${o.w}» وليس «${v.w}»، ارجعي إلى معجم الأبيات.`]),
  )
}

