export function makeInstructionFieldQuestion(): Question {
  const [text, field, why] = pick(FIELD_ROWS)
  const labels: Record<string, string> = { health: 'صحية', traffic: 'مرورية', religious: 'دينية' }
  const others = Object.keys(labels).filter((k) => k !== field)
  return choiceQ(
    `s2-ins-field-${text}`,
    `الإرشاد: «${text}»\nإلى أي مجال ينتمي؟`,
    [`إرشادات ${labels[field]}`, `صح! ${why}`],
    others.map((o): [string, string] => [`إرشادات ${labels[o]}`, `ليس مجالها «${labels[o]}»، فهي من الإرشادات ${labels[field]}.`]),
  )
}

