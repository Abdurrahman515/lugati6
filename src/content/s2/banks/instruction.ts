interface Sequence {
  topic: string
  steps: string[]
}

const SEQUENCES: Sequence[] = [
  {
    topic: 'غسل اليدين',
    steps: ['بلِّل يديك بالماء ثم ضع الصابون', 'افرك كفّيك وأصابعك جيداً', 'اشطف يديك بالماء', 'جفِّفهما بمنديل نظيف'],
  },
  {
    topic: 'عبور الشارع بأمان',
    steps: ['قف على الرصيف قبل النزول إلى الشارع', 'انظر يميناً ثم يساراً', 'اعبر من ممر المشاة أو عند الإشارة', 'امشِ دون استعمال الهاتف حتى تبلغ الرصيف الآخر'],
  },
  {
    topic: 'تجهيز الحقيبة المدرسية',
    steps: ['ضع جدول الغد أمامك', 'اختر الكتب والدفاتر حسب الجدول', 'رتّبها داخل الحقيبة', 'أغلق الحقيبة وضعها قرب الباب'],
  },
]

export function makeSequenceQuestion(): Question {
  const s = pick(SEQUENCES)
  const first = Math.random() < 0.5
  const right = first ? s.steps[0] : s.steps[s.steps.length - 1]
  const wrongs = s.steps.filter((x) => x !== right)
  return choiceQ(
    `s2-ins-seq-${s.topic}-${first ? 'first' : 'last'}`,
    `إرشادات «${s.topic}» تُرتَّب حسب التسلسل الزمني.\nأيّ إرشاد يأتي ${first ? 'أولاً' : 'أخيراً'}؟`,
    [right, `صح! هذا الإرشاد ${first ? 'يبدأ' : 'يُختم'} به التسلسل.`],
    wrongs.map((w): [string, string] => [w, `هذا الإرشاد يقع في وسط التسلسل وليس ${first ? 'أوله' : 'آخره'}.`]),
  )
}

