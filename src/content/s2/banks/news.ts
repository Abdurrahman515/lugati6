export function makeNewsSixQuestion(): Question {
  const set = pick(NEWS_SETS)
  const [frag, ans] = pick(set.parts)
  const others = shuffled(SIX.filter((s) => s !== ans)).slice(0, 3)
  return choiceQ(
    `s2-news-six-${frag}`,
    `في الخبر: «${set.sentence}»\nأيّ سؤال من الأسئلة الستة تجيب عنه عبارة «${frag}»؟`,
    [ans, `صح! عبارة «${frag}» تجيب عن السؤال ${ans}`],
    others.map((o): [string, string] => [o, `عبارة «${frag}» لا تجيب عن ${o}، بل عن ${ans}`]),
  )
}

