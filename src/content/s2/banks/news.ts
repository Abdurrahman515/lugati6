/** خطوات كتابة الخبر الصحفي بالترتيب */
const STEPS = [
  'البحث عن الخبر',
  'اختيار العنوان',
  'الإلمام بجوانب الخبر بالإجابة عن الأسئلة الستة',
  'إدراج مصدر الخبر',
  'توثيق الخبر بالصورة',
]

const STEP_MEANING: [string, string][] = [
  ['تقصّي الحدث بالمشاهدة والمقابلة مع من لهم صلة به وتصويره', STEPS[0]],
  ['وضع عبارة واضحة وجذابة بخط عريض بارز توحي بمضمون الخبر', STEPS[1]],
  ['كتابة موقع الخبر واسم وكالة الأنباء أو المندوب الصحفي', STEPS[3]],
  ['التقاط صورة من موقع الخبر وكتابة تعليق مناسب تحتها', STEPS[4]],
]

export function makeNewsStepQuestion(): Question {
  if (Math.random() < 0.5) {
    const k = Math.floor(Math.random() * (STEPS.length - 1))
    const wrongs = STEPS.filter((_, i) => i !== k + 1)
    return choiceQ(
      `s2-news-step-after-${k}`,
      `في كتابة الخبر الصحفي، ما الخطوة التي تأتي مباشرة بعد «${STEPS[k]}»؟`,
      [STEPS[k + 1], `صح! بعد «${STEPS[k]}» تأتي «${STEPS[k + 1]}».`],
      shuffled(wrongs)
        .slice(0, 3)
        .map((w): [string, string] => [w, `«${w}» ليست الخطوة التالية مباشرة بعد «${STEPS[k]}» في ترتيب الخطوات.`]),
    )
  }
  const [desc, step] = pick(STEP_MEANING)
  const wrongs = shuffled(STEPS.filter((s) => s !== step)).slice(0, 3)
  return choiceQ(
    `s2-news-step-mean-${step}`,
    `أيّ خطوة من خطوات كتابة الخبر هذه؟\n«${desc}»`,
    [step, `صح! هذا هو معنى «${step}».`],
    wrongs.map((w): [string, string] => [w, `هذه الخطوة مختلفة؛ الوصف المذكور يخص «${step}».`]),
  )
}