/* ───────── مرادف وضد ───────── */
const LEX = [
  { w: 'الفساد', syn: 'العطب', ant: 'الصلاح' },
  { w: 'القفل', syn: 'الغلق', ant: 'الفتح' },
  { w: 'الاعوجاج', syn: 'الانحناء', ant: 'الاستقامة' },
  { w: 'العافية', syn: 'الصحة', ant: 'المرض' },
]

export function makeLexQuestion(): Question {
  const e = pick(LEX)
  const kind = pick(['syn', 'ant'] as const)
  const label = kind === 'syn' ? 'مرادف' : 'ضد'
  const opposite = kind === 'syn' ? 'ضد' : 'مرادف'
  const right = e[kind]
  const other = kind === 'syn' ? e.ant : e.syn
  const stranger = pick(LEX.filter((x) => x !== e))
  const strangerWord = pick([stranger.syn, stranger.ant])
  return choiceQ(
    `s2-lex-${e.w}-${kind}`,
    `ما ${label} كلمة «${e.w}»؟`,
    [right, `صح! «${right}» ${label} «${e.w}».`],
    [
      [other, `«${other}» ${opposite} «${e.w}»، والمطلوب ${label}.`],
      [strangerWord, `«${strangerWord}» من عائلة «${stranger.w}» وما إلها علاقة بمعنى «${e.w}».`],
    ],
  )
}

/* ───────── الجمع ───────── */
const PLURALS: [string, string, [string, string]][] = [
  ['مُعَلَّب', 'مُعَلَّبَات', ['مَعَالِب', 'مُعَلَّبُون']],
  ['فِيتَامِين', 'فِيتَامِينَات', ['فَيَاتِين', 'فِيتَامِينُون']],
  ['وِعَاء', 'أَوْعِيَة', ['وِعَاءَات', 'وِعَاؤُون']],
  ['عُبُوَّة', 'عُبُوَّات', ['عَبَائِب', 'عُبُوَّون']],
  ['تِقْنِيَّة', 'تِقْنِيَّات', ['تَقَانِيّ', 'تِقْنِيُّون']],
  ['غِذَاء', 'أَغْذِيَة', ['غِذَاءَات', 'غِذَاؤُون']],
]

export function makePluralQuestion(): Question {
  const [s, right, wrongs] = pick(PLURALS)
  return choiceQ(
    `s2-plural-${s}`,
    `ما جمع كلمة «${s}»؟`,
    [right, `صح! جمع «${s}» هو «${right}».`],
    shuffled(wrongs).map((w) => [w, `«${w}» مش جمع «${s}» الصحيح. جمعها «${right}».`] as [string, string]),
  )
}