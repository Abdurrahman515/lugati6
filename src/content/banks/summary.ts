export function makeSummaryKeepQuestion(): Question {
  const entry = pick(SENTENCES)
  const [verdict, sentence, note] = entry
  const wrongs = shuffled((Object.keys(VERDICTS) as Verdict[]).filter((v) => v !== verdict)).slice(0, 3)
  return choiceQ(
    `sum-keep-${SENTENCES.indexOf(entry)}`,
    `أنتِ تلخّصين نصاً وصادفتِ هذه الجملة:\n«${sentence}»\nماذا تفعلين بها؟`,
    [VERDICTS[verdict], `صح! ${note}`],
    wrongs.map(
      (v) => [VERDICTS[v], `«${VERDICTS[v]}» مش مناسبة هون. ${note}`] as [string, string],
    ),
  )
}

