import type { ChoiceQuestion } from '../../types'
import { shuffled } from '../../lib/random'
import { choiceQ } from '../helpers'

type Fact = [prompt: string, right: [string, string], wrongs: [string, string][]]

function fromFacts(prefix: string, facts: Fact[]): () => ChoiceQuestion {
  return () => {
    const i = shuffled(facts.map((_, k) => k))[0]
    const [prompt, right, wrongs] = facts[i]
    return choiceQ(`${prefix}-${i}`, prompt, right, wrongs)
  }
}

