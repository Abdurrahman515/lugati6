export function makeDescriptionStyleQuestion(): Question {
  const pair = pick(STYLE_PAIRS)
  const [first, second, agr, opp] = pair
  const other = pick(STYLE_PAIRS.filter((p) => p[1] !== second))[1]
  return choiceQ(
    `desc-style-${STYLE_PAIRS.indexOf(pair)}`,
    `حوّلي الصفة «${first}» إلى أسلوب «الموصوف أولاً»:`,
    [second, `صح! «${second}»: بدأنا بالموصوف ثم جاءت الصفة مطابقة له.`],
    [
      [agr, `«${agr}» فيها خطأ تطابق: الصفة لازم تطابق الاسم اللي قبلها بالنوع والعدد.`],
      [opp, `«${opp}» بتغيّر المعنى، والمطلوب نفس الصفة بأسلوب مختلف.`],
      [other, `«${other}» وصف لشيء ثاني، مش نفس صفة «${first}».`],
    ],
  )
}

