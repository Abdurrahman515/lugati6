export function makeDescriptionPartQuestion(): Question {
  const entry = pick(PART_SENTENCES)
  const [part, sentence] = entry
  const right = PARTS[part]
  const wrongIds = shuffled((Object.keys(PARTS) as PartId[]).filter((p) => p !== part)).slice(0, 3)
  return choiceQ(
    `desc-part-${PART_SENTENCES.indexOf(entry)}`,
    `الجملة: «${sentence}»\nفي أي جزء من خريطة وصف الشخصية مكانُها؟`,
    [right.label, `صح! الجملة عن ${right.meaning}، فمكانها «${right.label}».`],
    wrongIds.map(
      (p) =>
        [
          PARTS[p].label,
          `«${PARTS[p].label}» بتخص ${PARTS[p].meaning}، أما الجملة هون فهي عن ${right.meaning}.`,
        ] as [string, string],
    ),
  )
}

