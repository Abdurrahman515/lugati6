export const PASSAGE_SETS: PassageSet[] = [PASSAGE_SHORE, PASSAGE_READER, PASSAGE_ZAID]

export const withPassage = (set: PassageSet, q: Question): Question => ({ ...q, passage: set.passage })

/** سؤال واحد من نص عشوائي، يحمل نصه معه (للمراجعة والاختبارات) */
export function makePassageQuestion(): Question {
  const set = pick(PASSAGE_SETS)
  return withPassage(set, pick(set.questions))
}