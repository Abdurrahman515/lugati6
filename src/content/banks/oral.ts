export function makeInterviewRoleQuestion(): Question {
  const entry = pick(LINES)
  const [isHost, line, note] = entry
  const host = 'المحاور'
  const guest = 'الضيف'
  return choiceQ(
    `oral-role-${LINES.indexOf(entry)}`,
    `في المقابلة الشفهية، من الذي يقول: «${line}»؟`,
    [isHost ? host : guest, `صح! ${note}`],
    [
      isHost
        ? [guest, 'الضيف هو اللي بيجيب ويردّ، مش اللي بيبدأ ويسأل ويشكر.']
        : [host, 'المحاور هو اللي بيبدأ ويسأل ويشكر، مش اللي بيجيب.'],
    ],
  )
}

