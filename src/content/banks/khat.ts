const build = (r: KhatRule): Question => choiceQ(`khat-${r.id}`, r.prompt, r.right, r.wrongs)

export const khatQuestion = (id: string): Question => {
  const r = RULES.find((x) => x.id === id)
  if (!r) throw new Error(`القاعدة غير موجودة: ${id}`)
  return build(r)
}

export function makeKhatQuestion(): Question {
  return build(pick(RULES))
}

export const LETTER_BUCKETS = [
  { id: 'on', label: 'مرتكزة على السطر', emoji: '🟰' },
  { id: 'down', label: 'جزء منها تحت السطر', emoji: '⬇️' },
]

const ON_LIST = '(أ ب ت ث د ذ ط ظ ف ك ه)'
const DOWN_LIST = '(ح ج خ ر ز س ش ص ض ع غ ق ل م ن هـ و ى)'

export function letterSortItems(on: string[], down: string[]): SortItem[] {
  return makeSortItems(LETTER_BUCKETS, [
    ...on.map((l): [string, string, string] => [l, 'on', `«${l}» من الحروف المرتكزة على السطر ${ON_LIST}.`]),
    ...down.map((l): [string, string, string] => [
      l,
      'down',
      `«${l}» من الحروف اللي بينزل جزء منها تحت السطر ${DOWN_LIST}.`,
    ]),
  ])
}