const verbQ = (id: string, verb: string, sentence: string, answer: string, wrongForm: string, wrongWhy: string) =>
  wq(
    id,
    `اكتبي مضارع الفعل «${verb}» في الفراغ:\n**${sentence}**`,
    answer,
    `قبل الهمزة حرف ${wrongWhy.startsWith('ألف') ? 'مفتوح' : 'مكسور'}، فتُكتب على ${answer.endsWith('ئ') ? 'ياء' : 'ألف'}: «${answer}».`,
    [{ text: wrongForm, why: wrongWhy }],
  )

